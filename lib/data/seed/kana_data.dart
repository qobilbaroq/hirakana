List<Kana> _build(String type) {
  final result = <Kana>[];
  for (final row in _rows) {
    final chars = (type == 'hiragana' ? row.$2 : row.$3).split(' ');
    final romaji = row.$4.split(' ');
    for (var i = 0; i < chars.length; i++) {
      result.add(Kana(
        id: '${type}_${romaji[i]}',
        character: chars[i],
        romaji: romaji[i],
        type: type,
        group: row.$1,
      ));
    }
  }
  return result;
}

